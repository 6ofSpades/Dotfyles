--[[
  hyprland.lua
  Converted from the classic hyprlang hyprland.conf to the Hyprland 0.55+ Lua config API.

  A few notes on this conversion (read before using):

  1. `source = ~/.config/theme/generated/hyprland.conf` was a file generated by an external
     theming tool and wasn't uploaded, so I can't see what it defines. It supplied `$border`,
     `$border_maximized`, and `$border_pin`. Below I `require()` it as if it had also been
     converted to Lua and returns a table of those values. If your theme tool still only
     outputs classic hyprlang, you'll need to either update the tool, or hand-convert that one
     generated file too (it's usually just a few color variables).
  2. Bind flag `u` isn't in Hyprland's officially documented classic flag list (l/r/e/n/m/t/i/s/d).
     Given how it's used throughout your keybindings (mostly on program-launcher binds), I've
     mapped it to the new `dont_inhibit = true` option, which is the closest semantic match.
     Double check this against `hyprctl binds` behavior after migrating.
  3. `plugin { hyprtrails { ... } }` is passed through `hl.config()` the same way other
     sections are, since the Lua docs say config categories map generically. If hyprtrails
     ships its own Lua bindings instead, check its docs.
]]

